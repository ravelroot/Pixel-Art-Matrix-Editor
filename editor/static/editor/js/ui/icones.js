export function caminhoBitmap(bitmap) {
  let d = '';
  bitmap.forEach((linha, y) => {
    let x = 0;
    while (x < linha.length) {
      if (linha[x] === '#') {
        let fim = x;
        while (fim < linha.length && linha[fim] === '#') fim++;
        d += `M${x} ${y}h${fim - x}v1h-${fim - x}z`;
        x = fim;
      } else x++;
    }
  });
  return d;
}

export function icone(nome, tamanho = 20, rotulo = '') {
  const bitmap = BITMAPS[nome];
  if (!bitmap) return '';
  const l = Math.max(...bitmap.map((r) => r.length));
  const a = bitmap.length;
  const lado = Math.max(l, a) + 2;
  const ox = (lado - l) / 2;
  const oy = (lado - a) / 2;
  const seguro = String(rotulo).replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);
  const aria = rotulo ? `role="img" aria-label="${seguro}"` : 'aria-hidden="true"';
  return `<svg class="icone" width="${tamanho}" height="${tamanho}" viewBox="${-ox} ${-oy} ${lado} ${lado}" shape-rendering="crispEdges" ${aria}><path fill="currentColor" d="${caminhoBitmap(bitmap)}"/></svg>`;
}
