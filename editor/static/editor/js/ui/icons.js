const generate = (l, a, fn) => {
  const m = Array.from({ length: a }, () => Array(l).fill('.'));
  fn((x, y) => {
    if (x >= 0 && y >= 0 && x < l && y < a) m[y][x] = '#';
  });
  return m.map((r) => r.join(''));
};

